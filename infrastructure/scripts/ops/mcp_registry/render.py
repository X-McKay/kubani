def _json(value):
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode()


def _yaml(docs):
    return (
        "# Generated by mcp-registry; edit infrastructure/mcp/backends instead.\n"
        + yaml.safe_dump_all(docs, sort_keys=False, explicit_start=True)
    ).encode()


def identity(d):
    return (
        d["apiVersion"],
        d["kind"],
        d.get("metadata", {}).get("namespace", ""),
        d["metadata"]["name"],
    )


def _object(api, kind, name, namespace, spec):
    return {
        "apiVersion": api,
        "kind": kind,
        "metadata": {"name": name, "namespace": namespace},
        "spec": spec,
    }


def _human_exclusions(entries):
    return sorted({"postgres-admin-mcp"} | {e["name"] + "-mcp" for e in entries})


def _peer(namespace, selector):
    return {
        "namespaceSelector": {
            "matchLabels": {"kubernetes.io/metadata.name": namespace}
        },
        "podSelector": {"matchLabels": selector},
    }


def _policy(name, namespace, selector, direction, peer, port):
    return _object(
        "networking.k8s.io/v1",
        "NetworkPolicy",
        name,
        namespace,
        {
            "podSelector": {"matchLabels": selector},
            "policyTypes": [direction],
            direction.lower(): [
                {
                    "from" if direction == "Ingress" else "to": [peer],
                    "ports": [{"port": port, "protocol": "TCP"}],
                }
            ],
        },
    )


def _backend_objects(root, e):
    n = e["name"]
    w = e["workload"]
    app = f"{n}-mcp"
    labels = {model.LABEL: app}
    route = f"agents-mcp-{n}"
    dep = json.loads((root / model.BASE / "profiles/container-sse-v1.json").read_text())
    dep["metadata"]["name"] = app
    dep["metadata"]["labels"] = labels
    dep["spec"]["selector"]["matchLabels"] = labels.copy()
    dep["spec"]["template"]["metadata"]["labels"] = labels.copy()
    c = dep["spec"]["template"]["spec"]["containers"][0]
    c.update(name=app, image=w["image"], args=w["args"], resources=w["resources"])
    c["ports"][0]["containerPort"] = w["port"]
    c["env"] = [
        {
            "name": v["name"],
            "valueFrom": {"secretKeyRef": deepcopy(v["secretKeyRef"])},
        }
        for v in w["secretEnv"]
    ]
    service = _object(
        "v1",
        "Service",
        app,
        "mcp",
        {
            "selector": labels.copy(),
            "ports": [
                {
                    "name": "http",
                    "port": w["port"],
                    "targetPort": "http",
                    "appProtocol": "agentgateway.dev/mcp",
                }
            ],
        },
    )
    service["metadata"]["labels"] = labels.copy()
    backend = _object(
        "agentgateway.dev/v1alpha1",
        "AgentgatewayBackend",
        route,
        "ai-gateway",
        {
            "mcp": {
                "failureMode": "FailClosed",
                "sessionRouting": "Stateless",
                "targets": [
                    {
                        "name": n,
                        "static": {
                            "host": f"{app}.mcp.svc.cluster.local",
                            "port": w["port"],
                            "path": "/sse",
                            "protocol": "SSE",
                        },
                    }
                ],
            }
        },
    )
    http = _object(
        "gateway.networking.k8s.io/v1",
        "HTTPRoute",
        route,
        "ai-gateway",
        {
            "parentRefs": [{"name": "agents", "sectionName": "agents-https"}],
            "hostnames": ["mcp.agents.internal"],
            "rules": [
                {
                    "matches": [{"path": {"type": "PathPrefix", "value": f"/{n}/mcp"}}],
                    "backendRefs": [
                        {
                            "group": "agentgateway.dev",
                            "kind": "AgentgatewayBackend",
                            "name": route,
                        }
                    ],
                }
            ],
        },
    )
    ref = {"group": "gateway.networking.k8s.io", "kind": "HTTPRoute", "name": route}
    ext = _object(
        "agentgateway.dev/v1alpha1",
        "AgentgatewayPolicy",
        f"agents-extauth-mcp-{n}",
        "ai-gateway",
        {
            "targetRefs": [ref],
            "traffic": {
                "extAuth": {
                    "backendRef": {
                        "kind": "Service",
                        "name": "agent-policy-service",
                        "namespace": "agent-platform",
                        "port": 9001,
                    },
                    "failureMode": "FailClosed",
                    "forwardBody": {"maxSize": 65536},
                    "grpc": {"contextExtensions": {"route": "mcp", "backend": n}},
                }
            },
        },
    )
    expressions = [
        f'jwt.client_type == "agent" && "{e["authorization"]["role"]}" in jwt.realm_access.roles && mcp.tool.name == "{tool}"'
        for tool in e["authorization"]["tools"]
    ]
    tools = _object(
        "agentgateway.dev/v1alpha1",
        "AgentgatewayPolicy",
        route + "-tools",
        "ai-gateway",
        {
            "targetRefs": [
                {
                    "group": "agentgateway.dev",
                    "kind": "AgentgatewayBackend",
                    "name": route,
                }
            ],
            "backend": {
                "mcp": {
                    "authorization": {
                        "action": "Allow",
                        "policy": {"matchExpressions": expressions},
                    }
                }
            },
        },
    )
    result = [dep, service, backend, http, ext, tools]
    for u in e["upstreams"]:
        result.append(
            _policy(
                f'allow-{app}-{u["name"]}-egress',
                "mcp",
                labels,
                "Egress",
                _peer(u["namespace"], u["selector"]),
                u["port"],
            )
        )
        result.append(
            _policy(
                f'allow-{app}-{u["name"]}',
                u["namespace"],
                u["selector"],
                "Ingress",
                _peer("mcp", labels),
                u["port"],
            )
        )
    # Existing namespace-wide agents rules already admit ports 8000/8080/8082.
    # Additional ports receive paired, Pod-scoped rules, never wider namespaces.
    if w["port"] not in (8000, 8080, 8082):
        result.append(
            _policy(
                f"allow-agents-{app}-ingress",
                "mcp",
                labels,
                "Ingress",
                _peer("ai-gateway", {model.LABEL: "agents"}),
                w["port"],
            )
        )
        result.append(
            _policy(
                f"allow-agents-{app}-egress",
                "ai-gateway",
                {model.LABEL: "agents"},
                "Egress",
                _peer("mcp", labels),
                w["port"],
            )
        )
    return result


def _owned(path):
    return (
        path == INVENTORY
        or path == "infrastructure/gitops/apps/keycloak/db-admin-backend.json"
        or any(path.startswith(r + "/") for r in ROOTS)
    )


def _read_inventory(root):
    path = model.safe_path(root, INVENTORY)
    if not path.exists():
        return None
    try:
        inv = json.loads(path.read_text())
    except (ValueError, OSError) as exc:
        raise ValueError("invalid generated inventory") from exc
    if (
        not isinstance(inv, dict)
        or inv.get("version") != 1
        or not isinstance(inv.get("files"), dict)
        or not isinstance(inv.get("backends"), dict)
    ):
        raise ValueError("invalid generated inventory")
    for p in inv["files"]:
        if not _owned(p) or p == INVENTORY:
            raise ValueError("unsafe inventoried output path")
        model.safe_path(root, p)
    return inv


def _source_documents(root):
    docs = []
    for path in sorted((root / "infrastructure/gitops").rglob("*.yaml")):
        relative = str(path.relative_to(root))
        if any(relative.startswith(r + "/") for r in ROOTS) or ".enc." in path.name:
            continue
        model.safe_path(root, relative)
        for d in model.yaml_documents(path):
            if (
                isinstance(d, dict)
                and d.get("kind") not in (None, "Kustomization")
                and d.get("metadata", {}).get("name")
            ):
                docs.append(d)
    return docs


def _validate_sources(root, entries, generated):
    sources = _source_documents(root)
    ids = {identity(d) for d in sources}
    for d in generated:
        if identity(d) in ids:
            raise ValueError(f"legacy/generated object collision: {identity(d)[1:]}")
    routes = [d for d in sources + generated if d["kind"] == "HTTPRoute"]
    used = set()
    for d in routes:
        for host in d["spec"].get("hostnames", []):
            for rule in d["spec"].get("rules", []):
                for match in rule.get("matches", []):
                    path = match.get("path", {}).get("value")
                    if not path:
                        continue
                    k = (d["metadata"].get("namespace"), host, path)
                    if k in used:
                        raise ValueError("route/path collision")
                    used.add(k)
    # Additive NetworkPolicy validation uses the complete Kustomize output in
    # validate_effective(), independent of source filenames and extensions.
    # Existing objects of other backend types remain handwritten and must retain
    # strict shared auth coverage; no generated replacement of their policy.
    auth = [
        d
        for d in sources
        if d["kind"] == "AgentgatewayPolicy"
        and d["metadata"]["name"] in ("agents-jwt", "agents-only")
    ]
    if len(auth) != 2:
        raise ValueError("shared authentication policies missing")
    baseline_auth = json.loads(
        (root / model.BASE / "baseline/shared-auth.json").read_text()
    )
    if sorted(auth, key=identity) != sorted(baseline_auth, key=identity):
        raise ValueError("shared authentication semantics changed")
    jwt = next(d for d in auth if d["metadata"]["name"] == "agents-jwt")["spec"][
        "traffic"
    ]["jwtAuthentication"]
    if jwt.get("mode") != "Strict" or jwt.get("preserveToken") is not True:
        raise ValueError("strict shared JWT required")
    only = next(d for d in auth if d["metadata"]["name"] == "agents-only")["spec"][
        "traffic"
    ]["authorization"]
    if only != {
        "action": "Allow",
        "policy": {
            "matchExpressions": [
                'jwt.client_type == "agent" && "agent-gateway" in jwt.aud'
            ]
        },
    }:
        raise ValueError("agents-only policy mismatch")
    managed = {f'agents-mcp-{e["name"]}' for e in entries}
    legacy = (
        {
            d["metadata"]["name"]
            for d in routes
            if d["metadata"].get("namespace") == "ai-gateway"
            and any(p.get("name") == "agents" for p in d["spec"].get("parentRefs", []))
        }
        - managed
        - {"agents-token"}
    )
    for p in auth:
        refs = [r["name"] for r in p["spec"]["targetRefs"]]
        if len(refs) != len(set(refs)) or not legacy <= set(refs):
            raise ValueError("missing or duplicate shared authentication coverage")
        if managed & set(refs):
            raise ValueError("generated authentication target still handwritten")


def render(root: Path, entries: list[dict]) -> dict[str, bytes]:
    root = Path(root)
    entries = deepcopy(entries)
    seen = set()
    roles = set()
    for e in entries:
        model.validate(e, root)
        if e["name"] in seen:
            raise ValueError("duplicate backend name")
        seen.add(e["name"])
        if e["authorization"]["role"] in roles:
            raise ValueError("duplicate backend role")
        roles.add(e["authorization"]["role"])
    entries.sort(key=lambda e: e["name"])
    inv = _read_inventory(root)
    if inv and set(inv["backends"]) - seen:
        raise ValueError(
            "backend removal/rename requires separately reviewed migration"
        )
    if inv:
        for e in entries:
            previous = inv["backends"].get(e["name"], {}).get("bootstrap")
            current = e.get("bootstrap")
            if previous and (
                not current
                or previous["sqlSha256"] != current["sqlSha256"]
                and previous["revision"] == current["revision"]
            ):
                raise ValueError("SQL hash changed without reviewed bootstrap revision")
    docs = [d for e in entries for d in _backend_objects(root, e)]
    ids = [identity(d) for d in docs]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate generated object identity")
    _validate_sources(root, entries, docs)
    files = {}
    groups = {
        MCP: [d for d in docs if d["metadata"]["namespace"] == "mcp"],
        GW: [d for d in docs if d["metadata"]["namespace"] == "ai-gateway"],
        NET: [
            d for d in docs if d["metadata"]["namespace"] not in ("mcp", "ai-gateway")
        ],
    }
    for folder, items in groups.items():
        files[folder + "/backends.yaml"] = _yaml(items)
        files[folder + "/kustomization.yaml"] = _yaml(
            [
                {
                    "apiVersion": "kustomize.config.k8s.io/v1beta1",
                    "kind": "Kustomization",
                    "resources": ["backends.yaml"],
                }
            ]
        )
    refs = [
        {
            "group": "gateway.networking.k8s.io",
            "kind": "HTTPRoute",
            "name": f'agents-mcp-{e["name"]}',
        }
        for e in entries
    ]
    for policy in ("agents-jwt", "agents-only"):
        files[GW + "/" + policy + "-targets.json"] = _json(
            [{"op": "add", "path": "/spec/targetRefs/-", "value": ref} for ref in refs]
        )
    files[MCP + "/human-exclusions.json"] = _json(
        [
            {
                "op": "replace",
                "path": "/spec/podSelector/matchExpressions/0/values",
                "value": _human_exclusions(entries),
            }
        ]
    )
    for e in entries:
        files[IDENT + "/" + e["name"] + ".json"] = _json(model.descriptor(e))
        if e["name"] == "postgres-admin":
            files["infrastructure/gitops/apps/keycloak/db-admin-backend.json"] = _json(
                model.descriptor(e)
            )
    records = {
        e["name"]: {"profile": e["profile"], "bootstrap": e.get("bootstrap")}
        for e in entries
    }
    inventory = {
        "version": 1,
        "backends": records,
        "files": {
            p: "sha256:" + hashlib.sha256(v).hexdigest()
            for p, v in sorted(files.items())
        },
        "objects": [
            dict(zip(("apiVersion", "kind", "namespace", "name"), i))
            for i in sorted(ids)
        ],
    }
    files[INVENTORY] = _json(inventory)
    for path in files:
        if not _owned(path):
            raise ValueError("unsafe generated path")
        model.safe_path(root, path)
    for p in files:
        if (
            p == INVENTORY
            or p == "infrastructure/gitops/apps/keycloak/db-admin-backend.json"
        ):
            continue
        if (root / p).exists() and (not inv or p not in inv["files"]):
            raise ValueError("preexisting unowned output collision: " + p)
    if inv and set(inv["files"]) - set(files):
        raise ValueError("stale inventory output; migration required")
    for folder in ROOTS:
        p = model.safe_path(root, folder)
        if p.exists():
            for child in p.rglob("*"):
                if child.is_symlink():
                    raise ValueError("symlink generated path")
                if child.is_file() and str(child.relative_to(root)) not in files:
                    raise ValueError("unaccounted stale generated output")
    return files


def build(root):
    result = []
    for path in BUILD_ROOTS:
        run = subprocess.run(
            ["kubectl", "kustomize", str(root / path)],
            capture_output=True,
            text=True,
            timeout=90,
        )
        if run.returncode:
            raise ValueError(f"Kustomize failed for {path}: " + run.stderr[:800])
        result.extend(d for d in yaml.safe_load_all(run.stdout) if d)
    ids = [identity(d) for d in result]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate identity across complete Kustomizations")
    return result


def _resolve_service(
    docs, namespace, service_name, port, source_namespace="ai-gateway"
):
    service = next(
        (
            d
            for d in docs
            if d["kind"] == "Service"
            and d["metadata"].get("namespace") == namespace
            and d["metadata"]["name"] == service_name
        ),
        None,
    )
    if service is None:
        raise ValueError(
            "referenced Service missing: " + namespace + "/" + service_name
        )
    ports = [
        p
        for p in service["spec"].get("ports", [])
        if p.get("port") == port and p.get("protocol", "TCP") == "TCP"
    ]
    if len(ports) != 1:
        raise ValueError("referenced Service port missing or ambiguous")
    selector = service["spec"].get("selector")
    if not selector:
        raise ValueError("referenced Service requires explicit Pod selector")
    workloads = [
        d
        for d in docs
        if d["kind"] in ("Deployment", "StatefulSet")
        and d["metadata"].get("namespace") == namespace
        and all(
            d["spec"]["template"]["metadata"].get("labels", {}).get(k) == v
            for k, v in selector.items()
        )
    ]
    target = ports[0].get("targetPort", port)
    if not workloads or not all(
        any(
            (
                p.get("name") == target
                if isinstance(target, str)
                else p.get("containerPort") == target
            )
            for c in d["spec"]["template"]["spec"]["containers"]
            for p in c.get("ports", [])
        )
        for d in workloads
    ):
        raise ValueError("referenced Service target port/workload mismatch")
    if namespace != source_namespace:
        grants = [
            d
            for d in docs
            if d["kind"] == "ReferenceGrant"
            and d["metadata"].get("namespace") == namespace
        ]
        if not any(
            any(
                v
                == {
                    "group": "agentgateway.dev",
                    "kind": "AgentgatewayPolicy",
                    "namespace": source_namespace,
                }
                for v in d["spec"].get("from", [])
            )
            and any(
                v.get("group", "") == ""
                and v.get("kind") == "Service"
                and v.get("name", service_name) == service_name
                for v in d["spec"].get("to", [])
            )
            for d in grants
        ):
            raise ValueError("cross-namespace policy Service ReferenceGrant missing")


def _validate_platform(docs):
    gateway = next(
        (
            d
            for d in docs
            if d["kind"] == "Gateway"
            and d["metadata"].get("namespace") == "ai-gateway"
            and d["metadata"]["name"] == "agents"
        ),
        None,
    )
    if gateway is None or gateway["spec"].get("gatewayClassName") != "agentgateway":
        raise ValueError("agents Gateway missing or wrong class")
    listeners = [
        listener
        for listener in gateway["spec"].get("listeners", [])
        if listener.get("name") == "agents-https"
    ]
    if (
        len(listeners) != 1
        or listeners[0].get("protocol") != "HTTPS"
        or listeners[0].get("port") != 443
        or listeners[0].get("tls", {}).get("mode") != "Terminate"
        or listeners[0].get("allowedRoutes", {}).get("namespaces", {}).get("from")
        != "Same"
    ):
        raise ValueError("agents HTTPS listener missing or incompatible")
    _resolve_service(docs, "agent-platform", "agent-policy-service", 9001)
    _resolve_service(docs, "auth", "keycloak", 8080)


def validate_effective(root, entries, docs):
    _validate_platform(docs)
    by_id = {identity(d): d for d in docs}
    namespaces = {"mcp", "ai-gateway", "auth", "agent-platform"} | {
        u["namespace"] for e in entries for u in e["upstreams"]
    }
    baseline = json.loads(
        (root / model.BASE / "baseline/effective-network-policies.json").read_text()
    )
    expected_policies = {}
    for wanted in baseline:
        if wanted["metadata"].get("namespace") not in namespaces:
            continue
        if (
            wanted["metadata"]["name"] == "allow-ai-gateway-ingress"
            and wanted["metadata"]["namespace"] == "mcp"
        ):
            wanted = deepcopy(wanted)
            wanted["spec"]["podSelector"]["matchExpressions"][0]["values"] = (
                _human_exclusions(entries)
            )
        expected_policies[identity(wanted)] = wanted
    for entry in entries:
        for wanted in _backend_objects(root, entry):
            if wanted["kind"] != "NetworkPolicy":
                continue
            key = identity(wanted)
            if key in expected_policies and expected_policies[key] != wanted:
                raise ValueError(
                    "generated policy changes reviewed network baseline: " + str(key)
                )
            expected_policies[key] = wanted
    actual_policies = {
        identity(d): d
        for d in docs
        if d["kind"] == "NetworkPolicy" and d["metadata"].get("namespace") in namespaces
    }
    unexpected = sorted(actual_policies.keys() - expected_policies.keys())
    missing = sorted(expected_policies.keys() - actual_policies.keys())
    changed = sorted(
        k
        for k in actual_policies.keys() & expected_policies.keys()
        if actual_policies[k] != expected_policies[k]
    )
    if unexpected or missing or changed:
        raise ValueError(
            "effective additive NetworkPolicy set differs: "
            + str(
                {
                    "unexpected": unexpected[:5],
                    "missing": missing[:5],
                    "changed": changed[:5],
                }
            )
        )
    for wanted in json.loads(
        (root / model.BASE / "baseline/shared-auth.json").read_text()
    ):
        wanted["spec"]["targetRefs"] += [
            {
                "group": "gateway.networking.k8s.io",
                "kind": "HTTPRoute",
                "name": f'agents-mcp-{e["name"]}',
            }
            for e in entries
        ]
        if by_id.get(identity(wanted)) != wanted:
            raise ValueError(
                "effective shared authentication differs from exact desired policy"
            )
    for e in entries:
        for wanted in _backend_objects(root, e):
            if by_id.get(identity(wanted)) != wanted:
                raise ValueError(
                    "effective generated object differs or is excluded: "
                    + str(identity(wanted))
                )
        route = f'agents-mcp-{e["name"]}'
        for p in ("agents-jwt", "agents-only"):
            policy = next(
                (
                    d
                    for d in docs
                    if d["kind"] == "AgentgatewayPolicy" and d["metadata"]["name"] == p
                ),
                None,
            )
            if not policy or route not in [
                r["name"] for r in policy["spec"]["targetRefs"]
            ]:
                raise ValueError("effective route missing shared auth")
        human = next(
            d
            for d in docs
            if d["kind"] == "NetworkPolicy"
            and d["metadata"]["namespace"] == "mcp"
            and d["metadata"]["name"] == "allow-ai-gateway-ingress"
        )
        if (
            e["name"] + "-mcp"
            not in human["spec"]["podSelector"]["matchExpressions"][0]["values"]
        ):
            raise ValueError("human gateway exclusion missing")
        if "bootstrap" in e:
            b = e["bootstrap"]
            job = next(
                d
                for d in model.yaml_documents(model.safe_path(root, b["manifest"]))
                if d["kind"] == "Job"
            )
            if by_id.get(identity(job)) != job:
                raise ValueError("bootstrap Job missing/changed in complete output")
            cm = next(
                (
                    d
                    for d in docs
                    if d["kind"] == "ConfigMap"
                    and d["metadata"]["name"] == b["configMap"]
                    and d["metadata"].get("namespace") == b["namespace"]
                ),
                None,
            )
            if (
                not cm
                or cm.get("data", {}).get(b["key"])
                != model.safe_path(root, b["sql"]).read_text()
            ):
                raise ValueError("bootstrap ConfigMap/SQL mismatch")


def _stage(root, files):
    temp = tempfile.TemporaryDirectory(prefix="mcp-registry-")
    staged = Path(temp.name)
    shutil.copytree(root / "infrastructure", staged / "infrastructure", symlinks=True)
    for p, data in files.items():
        path = model.safe_path(staged, p)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return temp, staged


def write(root: Path) -> None:
    root = Path(root)
    entries = model.load_registry(root)
    files = render(root, entries)
    temp, staged = _stage(root, files)
    try:
        validate_effective(staged, entries, build(staged))
    finally:
        temp.cleanup()
    # Prepare every replacement before touching an existing file. Roll back on
    # errors; inventory is replaced last, so interrupted writes remain detectable.
    old = {p: (root / p).read_bytes() if (root / p).exists() else None for p in files}
    prepared = {}
    replaced = []
    try:
        for p, data in files.items():
            target = model.safe_path(root, p)
            target.parent.mkdir(parents=True, exist_ok=True)
            fd, path = tempfile.mkstemp(prefix=".mcp-", dir=target.parent)
            with os.fdopen(fd, "wb") as stream:
                stream.write(data)
                stream.flush()
                os.fsync(stream.fileno())
            os.chmod(
                path, (target.stat().st_mode & 0o777) if target.exists() else 0o644
            )
            prepared[p] = path
        for p in sorted(files, key=lambda p: (p == INVENTORY, p)):
            os.replace(prepared[p], model.safe_path(root, p))
            replaced.append(p)
    except BaseException:
        for p in reversed(replaced):
            target = root / p
            if old[p] is None:
                target.unlink(missing_ok=True)
            else:
                target.write_bytes(old[p])
        raise
    finally:
        for p in prepared.values():
            Path(p).unlink(missing_ok=True)


def objects(root: Path, name: str) -> list[dict]:
    entries = model.load_registry(root)
    entry = next((e for e in entries if e["name"] == name), None)
    if entry is None:
        raise ValueError("unknown backend")
    render(root, entries)  # Validate ownership and references before status use.
    result = _backend_objects(root, entry)
    auth = model.yaml_documents(
        root / "infrastructure/gitops/apps/ai-gateway/agents/policies-auth.yaml"
    )
    for d in auth:
        if d["metadata"]["name"] in ("agents-jwt", "agents-only"):
            d = deepcopy(d)
            d["spec"]["targetRefs"] += [
                {
                    "group": "gateway.networking.k8s.io",
                    "kind": "HTTPRoute",
                    "name": f'agents-mcp-{e["name"]}',
                }
                for e in entries
            ]
            result.append(d)
    # Shared effective paths are explicit in registration status, including the
    # broader existing agents ingress/egress and DNS, never Secret data.
    baseline = json.loads(
        (root / model.BASE / "baseline/effective-network-policies.json").read_text()
    )
    for d in baseline:
        if (d["metadata"].get("namespace"), d["metadata"]["name"]) == (
            "mcp",
            "allow-ai-gateway-ingress",
        ):
            d = deepcopy(d)
            d["spec"]["podSelector"]["matchExpressions"][0]["values"] = (
                _human_exclusions(entries)
            )
            result.append(d)
        if (d["metadata"].get("namespace"), d["metadata"]["name"]) in {
            ("mcp", "allow-agents-gateway-ingress"),
            ("mcp", "allow-dns-egress"),
            ("ai-gateway", "agents-data-plane-egress"),
        }:
            result.append(d)
    if "bootstrap" in entry:
        b = entry["bootstrap"]
        result += [
            d
            for d in model.yaml_documents(model.safe_path(root, b["manifest"]))
            if d["kind"] == "Job"
        ]
        result.append(
            {
                "apiVersion": "v1",
                "kind": "ConfigMap",
                "metadata": {"name": b["configMap"], "namespace": b["namespace"]},
                "data": {b["key"]: model.safe_path(root, b["sql"]).read_text()},
            }
        )
    return result
